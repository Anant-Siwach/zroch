import AppKit

struct ClipItem: Codable, Identifiable, Hashable {
    var id = UUID()
    var text: String
    var date = Date()
    var pinned = false
}

struct Snippet: Codable, Identifiable, Hashable {
    var id = UUID()
    var title: String
    var text: String
}

/// Clipboard history (text) and saved snippets.
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published var history: [ClipItem] = Storage.load([ClipItem].self, from: "clipboard.json") ?? []
    @Published var snippets: [Snippet] = Storage.load([Snippet].self, from: "snippets.json") ?? []

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    /// Password managers mark secrets with these types; never record them.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if let types = pb.types, types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }
        guard let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        insert(text)
    }

    private func insert(_ text: String) {
        var item = ClipItem(text: text)
        if let idx = history.firstIndex(where: { $0.text == text }) {
            item.pinned = history[idx].pinned
            history.remove(at: idx)
        }
        history.insert(item, at: 0)
        let limit = max(5, UserDefaults.standard.integer(forKey: Prefs.clipboardLimit))
        var unpinned = 0
        history = history.filter { $0.pinned || { unpinned += 1; return unpinned <= limit }() }
        saveHistory()
    }

    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChange = pb.changeCount
        insert(text)
    }

    func togglePin(_ item: ClipItem) {
        guard let i = history.firstIndex(of: item) else { return }
        history[i].pinned.toggle()
        saveHistory()
    }

    func delete(_ item: ClipItem) {
        history.removeAll { $0.id == item.id }
        saveHistory()
    }

    func clearHistory() {
        history.removeAll { !$0.pinned }
        saveHistory()
    }

    func addSnippet(title: String, text: String) {
        snippets.append(Snippet(title: title.isEmpty ? String(text.prefix(24)) : title, text: text))
        Storage.save(snippets, to: "snippets.json")
    }

    func deleteSnippet(_ s: Snippet) {
        snippets.removeAll { $0.id == s.id }
        Storage.save(snippets, to: "snippets.json")
    }

    var sortedHistory: [ClipItem] { history.filter(\.pinned) + history.filter { !$0.pinned } }

    private func saveHistory() { Storage.save(history, to: "clipboard.json") }
}
